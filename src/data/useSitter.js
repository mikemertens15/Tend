import { useState, useEffect, useCallback, useMemo } from 'react';
import { supabase } from '../lib/supabase';
import { useHousehold } from '../household/HouseholdProvider';
import { parseDay, daysUntil, monthDay } from '../dates';
import { dueStatus, intervalLabel } from './cadence';

// Two hooks either side of the same link.
//
// useSitterPage runs on the *public* page with no session at all: it calls one
// SECURITY DEFINER function with the token and gets back a fixed shape. It
// never touches a table directly, which is what keeps a leaked link to "one
// household's pet routine" rather than an open door.

const MEAL_SLOTS = {
  1: [['day', 'Fed']],
  2: [
    ['am', 'Morning'],
    ['pm', 'Evening'],
  ],
  3: [
    ['am', 'Morning'],
    ['mid', 'Midday'],
    ['pm', 'Evening'],
  ],
  4: [
    ['am', 'Morning'],
    ['mid', 'Midday'],
    ['pm', 'Evening'],
    ['night', 'Night'],
  ],
};

export function useSitterPage(token) {
  const [data, setData] = useState(undefined); // undefined = loading, null = bad link
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => {
    const { data: page, error } = await supabase.rpc('sitter_page', { p_token: token });
    setData(error ? null : (page ?? null));
  }, [token]);

  useEffect(() => {
    load();
  }, [load]);

  const pets = useMemo(
    () =>
      (data?.pets ?? []).map((p) => {
        const slots = MEAL_SLOTS[p.mealsPerDay] ?? MEAL_SLOTS[2];
        const meals = slots.map(([slot, label]) => {
          const hit = (p.fed ?? []).find((f) => f.slot === slot);
          return { slot, label, fed: Boolean(hit), by: hit?.by ?? null };
        });
        return { ...p, meals, allFed: meals.every((m) => m.fed) };
      }),
    [data],
  );

  const care = useMemo(
    () =>
      (data?.care ?? [])
        .map((c) => {
          const s = dueStatus(c.lastDoneOn, c.intervalDays);
          return {
            ...c,
            tone: s.tone,
            status: s.status,
            daysLeft: s.daysLeft,
            cadence: intervalLabel(c.intervalDays),
          };
        })
        .sort((a, b) => a.daysLeft - b.daysLeft),
    [data],
  );

  const upcoming = useMemo(
    () =>
      (data?.upcoming ?? []).map((e) => ({
        ...e,
        dateLabel: monthDay(parseDay(e.onDate)),
        daysLeft: daysUntil(parseDay(e.onDate)),
      })),
    [data],
  );

  // The sitter ticking a meal off is the point of this being a page rather
  // than a printout — reload rather than patch locally, so two people looking
  // at the same link converge.
  const toggleMeal = useCallback(
    async (petId, slot) => {
      if (busy) return;
      setBusy(true);
      await supabase.rpc('sitter_toggle_meal', { p_token: token, p_pet_id: petId, p_slot: slot });
      await load();
      setBusy(false);
    },
    [token, busy, load],
  );

  return { page: data, pets, care, upcoming, loading: data === undefined, toggleMeal, busy };
}

// The owner's side: create, revoke and delete links.
export function useShareLinks() {
  const { household } = useHousehold();
  const householdId = household?.id ?? null;
  const [links, setLinks] = useState([]);
  const [loading, setLoading] = useState(true);

  const fetchLinks = useCallback(async () => {
    if (!householdId) {
      setLinks([]);
      setLoading(false);
      return;
    }
    const { data } = await supabase
      .from('share_links')
      .select('*')
      .eq('household_id', householdId)
      .order('created_at', { ascending: false });
    setLinks(data ?? []);
    setLoading(false);
  }, [householdId]);

  useEffect(() => {
    fetchLinks();
  }, [fetchLinks]);

  const createLink = useCallback(
    async (fields) => {
      if (!householdId) return null;
      // The token itself is generated by the database default, so it never
      // depends on the browser's randomness.
      const { data, error } = await supabase
        .from('share_links')
        .insert({ household_id: householdId, ...fields })
        .select()
        .single();
      if (error) return null;
      fetchLinks();
      return data;
    },
    [householdId, fetchLinks],
  );

  const revokeLink = useCallback(
    async (id) => {
      setLinks((ls) => ls.map((l) => (l.id === id ? { ...l, revoked: true } : l)));
      const { error } = await supabase.from('share_links').update({ revoked: true }).eq('id', id);
      if (error) fetchLinks();
    },
    [fetchLinks],
  );

  const deleteLink = useCallback(
    async (id) => {
      setLinks((ls) => ls.filter((l) => l.id !== id));
      const { error } = await supabase.from('share_links').delete().eq('id', id);
      if (error) fetchLinks();
    },
    [fetchLinks],
  );

  return { links, loading, createLink, revokeLink, deleteLink };
}

export const sitterUrl = (token) => `${window.location.origin}/#/sitter/${token}`;
